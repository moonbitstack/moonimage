"""Generating the PNG fixtures from PngSuite.

    python scripts/fixtures/png.py

PngSuite ships a reference decoding of every image it contains, as a JSON array
of red, green, blue and alpha per pixel. That is the whole oracle: the library
decodes each file, widens the result to sixteen-bit RGBA, and has to land on a
digest of the reference. The files whose names start with `x` are the ones
PngSuite says are invalid, and every one of those has to be refused.

Nothing here goes through this library's own writer, so a mistake in the encoder
cannot make a decoder test pass.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import moonbit
import sources

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "png" / "suite_test.mbt"


def reference_bytes(values: list[int], sixteen_bit: bool) -> bytes:
    """The reference pixels as sixteen-bit RGBA, big-endian."""
    out = bytearray()
    for index in range(0, len(values) - 3, 4):
        for channel in range(4):
            value = values[index + channel]
            if not sixteen_bit:
                value = value * 257
            out += value.to_bytes(2, "big")
    return bytes(out)


def main() -> None:
    images = sources.png_suite()
    references = sources.png_suite_reference()

    valid = []
    invalid = []
    missing = []
    for name in sorted(images):
        if name.startswith("x"):
            invalid.append((name, images[name]))
            continue
        if name not in references:
            missing.append(name)
            continue
        values = references[name]
        # A file whose name ends in 16 is sixteen bits deep; everything else is
        # eight, and its values are scaled into the same digest.
        sixteen_bit = name.endswith("16")
        pixels = reference_bytes(values, sixteen_bit)
        valid.append((name, images[name], moonbit.digest(pixels)))

    body = []
    body.append("let png_suite : Array[(String, Bytes)] = [")
    for name, data, _ in valid:
        body.append(
            "  (\n    %s,\n    %s,\n  )," % ('"%s"' % name, moonbit.literal(data))
        )
    body.append("]\n")

    body.append("let png_suite_expected : Array[(String, String)] = [")
    for name, _, expected in valid:
        body.append('  ("%s", "%s"),' % (name, expected))
    body.append("]\n")

    body.append("let png_suite_invalid : Array[(String, Bytes)] = [")
    for name, data in invalid:
        body.append(
            "  (\n    %s,\n    %s,\n  )," % ('"%s"' % name, moonbit.literal(data))
        )
    body.append("]")

    header = """\
// Generated by scripts/fixtures/png.py. Do not edit.
//
// Every image of PngSuite, with a digest of the reference decoding published
// beside it, and the files PngSuite calls invalid. The digest is over
// sixteen-bit RGBA, so an eight-bit file and a sixteen-bit one are compared the
// same way and a conversion that loses a bit shows up as a mismatch."""
    moonbit.write(TARGET, header, "\n".join(body))
    if missing:
        print("no reference pixels for: %s" % ", ".join(missing))


if __name__ == "__main__":
    main()
