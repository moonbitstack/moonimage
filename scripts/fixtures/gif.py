"""Generating the GIF fixtures.

    python scripts/fixtures/gif.py

Pillow writes the files; Pillow reads them back frame by frame, compositing each
according to the disposal rule the file declares. That composition is the
reference: our decoder has to produce the same pixels at each step, and the same
delay. An animation whose disposal rule is misread shows the previous frame
bleeding through, which is exactly what a per-frame digest catches.
"""

import io
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import moonbit
import sources

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "gif" / "samples_test.mbt"


def save(image: Image.Image, **options) -> bytes:
    handle = io.BytesIO()
    image.save(handle, format="GIF", **options)
    return handle.getvalue()


def frames_of(data: bytes) -> list[tuple[int, str]]:
    """Every composited frame: its delay in milliseconds, and its pixels."""
    image = Image.open(io.BytesIO(data))
    frames = []
    index = 0
    while True:
        try:
            image.seek(index)
        except EOFError:
            break
        frame = image.convert("RGBA")
        delay = image.info.get("duration", 0)
        frames.append((int(delay) // 10 * 10, moonbit.digest(frame.tobytes())))
        index += 1
        if index > 64:
            break
    return frames


def stills():
    cases = []
    base = sources.pattern(48, 32)
    palette = base.convert("RGB").quantize(colors=64)

    cases.append(("pillow-static", save(palette)))
    # A colour table with fewer than 256 entries, which is where a decoder that
    # assumes eight bits goes wrong.
    cases.append(("pillow-four-colours", save(base.convert("RGB").quantize(colors=4))))
    cases.append(("pillow-grey", save(base.convert("L"))))
    # One transparent colour, which GIF has instead of an alpha channel.
    transparent = base.convert("RGBA")
    pixels = transparent.load()
    for y in range(transparent.height):
        for x in range(transparent.width // 2):
            pixels[x, y] = (0, 0, 0, 0)
    cases.append(("pillow-transparent", save(transparent, transparency=0)))
    return [(name, data, frames_of(data)[0][1]) for name, data in cases]


def animations():
    cases = []
    width, height = 40, 30
    plain = sources.pattern(width, height).convert("RGB")
    modified = plain.copy()
    modified.paste((255, 0, 0), (4, 4, 20, 20))
    another = plain.copy()
    another.paste((0, 0, 255), (20, 10, 36, 26))
    base = plain.quantize(colors=32)
    second = modified.quantize(colors=32)
    third = another.quantize(colors=32)
    data = save(
        base,
        save_all=True,
        append_images=[second, third],
        duration=[120, 80, 40],
        loop=2,
        disposal=[1, 2, 1],
    )
    cases.append(("pillow-animation", data))

    # An animation where one frame is smaller than the canvas, which is where the
    # rectangle's offset matters.
    small = Image.new("RGB", (10, 8), (0, 200, 0))
    small = small.quantize(colors=16)
    cases.append((
        "pillow-offset",
        save(
            base,
            save_all=True,
            append_images=[small],
            duration=[100, 100],
            loop=0,
        ),
    ))
    # Interlaced, if Pillow will write it.
    try:
        interlaced = save(base, interlace=True)
        cases.append(("pillow-interlaced", interlaced))
    except Exception as error:  # noqa: BLE001 - the option is not always there
        print("interlaced GIF not written: %s" % error)
    return [(name, data, frames_of(data)) for name, data in cases]


def main() -> None:
    still = stills()
    animated = animations()

    body = ["let samples : Array[(String, Bytes, String)] = ["]
    for name, data, expected in still:
        body.append(
            "  (\n    %s,\n    %s,\n    %s,\n  ),"
            % ('"%s"' % name, moonbit.literal(data), '"%s"' % expected)
        )
    body.append("]\n")

    body.append("let animations : Array[(String, Bytes, Array[(Int, String)])] = [")
    for name, data, frames in animated:
        rendered = ", ".join('(%d, "%s")' % (delay, digest) for delay, digest in frames)
        body.append(
            "  (\n    %s,\n    %s,\n    [%s],\n  ),"
            % ('"%s"' % name, moonbit.literal(data), rendered)
        )
    body.append("]")

    header = """\
// Generated by scripts/fixtures/gif.py. Do not edit.
//
// GIF files Pillow wrote, with the composited pixels Pillow reads back from them:
// one digest per still image, and a delay and a digest per frame of an animation.
// Reading the disposal rule wrong is what a per-frame digest catches."""
    moonbit.write(TARGET, header, "\n".join(body))


if __name__ == "__main__":
    main()
