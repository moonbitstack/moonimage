"""Generating the JPEG fixtures.

    python scripts/fixtures/jpeg.py

JPEG is lossy, so there is no digest to compare: the reference is the picture
Pillow decodes, carried as a PNG, and the test measures how far ours is from it.
Two decoders of the same file are allowed to differ by a step or two — the
transform and the colour conversion are specified to a rounding, not bit for bit —
and the tolerance in the fixture is that allowance and nothing more.

Shapes covered: baseline at three subsamplings, progressive, greyscale, a restart
interval, and an EXIF orientation tag.
"""

import io
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import moonbit
import sources

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "jpeg" / "samples_test.mbt"


def save(image: Image.Image, **options) -> bytes:
    handle = io.BytesIO()
    image.save(handle, format="JPEG", **options)
    return handle.getvalue()


def reference(data: bytes) -> bytes:
    decoded = Image.open(io.BytesIO(data))
    decoded.load()
    return moonbit.png_of(decoded.convert("RGB"))


def orientation_bytes(value: int) -> bytes:
    """A minimal EXIF block with one orientation tag, big-endian."""
    tiff = bytearray()
    tiff += b"MM\x00\x2a"
    tiff += (8).to_bytes(4, "big")
    tiff += (1).to_bytes(2, "big")
    tiff += (0x0112).to_bytes(2, "big")
    tiff += (3).to_bytes(2, "big")
    tiff += (1).to_bytes(4, "big")
    tiff += value.to_bytes(2, "big") + b"\x00\x00"
    tiff += (0).to_bytes(4, "big")
    return b"Exif\x00\x00" + bytes(tiff)


def main() -> None:
    cases = []
    base = sources.pattern(64, 48).convert("RGB")

    # The allowance is a few steps: two decoders of the same file differ in the
    # rounding of the transform and of the colour conversion, and in nothing
    # else.
    cases.append(("baseline-444", save(base, quality=90, subsampling=0), 4))
    cases.append(("baseline-420", save(base, quality=75, subsampling=2), 6))
    cases.append(("baseline-422", save(base, quality=85, subsampling=1), 6))
    cases.append(("progressive", save(base, quality=90, progressive=True), 6))
    cases.append(("greyscale", save(base.convert("L"), quality=90), 4))
    cases.append(("low-quality", save(base, quality=20), 8))
    # A size that is not a multiple of the block grid: the last block on each
    # axis is padded, and how a decoder fills it is not specified, so the edge
    # can differ by more than the middle does.
    cases.append(("odd-size", save(base.crop((0, 0, 37, 23)), quality=90), 32))

    # A file that says it is rotated a quarter turn.
    turned = save(base, quality=90, exif=orientation_bytes(6))
    cases.append(("exif-rotate90", turned, 4))

    body = ["let samples : Array[(String, Bytes, Bytes, Int)] = ["]
    for name, data, tolerance in cases:
        body.append(
            "  (\n    %s,\n    %s,\n    %s,\n    %d,\n  ),"
            % (
                '"%s"' % name,
                moonbit.literal(data),
                moonbit.literal(reference(data)),
                tolerance,
            )
        )
    body.append("]")

    header = """\
// Generated by scripts/fixtures/jpeg.py. Do not edit.
//
// JPEG files Pillow wrote, each with the picture Pillow decodes from it, carried
// as a PNG because that is lossless, and the number of steps two decoders are
// allowed to disagree by. Reading ours against that picture is the test."""
    moonbit.write(TARGET, header, "\n".join(body))


if __name__ == "__main__":
    main()
