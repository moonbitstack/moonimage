"""Generating the Huffman tables the JPEG writer uses.

    python scripts/fixtures/jpeg_tables.py

The four tables of the standard are long lists of numbers, and typing them out is
how an encoder comes to produce files no decoder can read. They are taken instead
from a file a mature encoder wrote: Pillow, which uses the tables the standard
publishes as an example. Reading them back out is the same as quoting them, but
without the typo.
"""

import io
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import moonbit

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "jpeg" / "tables.mbt"


def segments(data: bytes):
    position = 2
    while position + 4 <= len(data):
        if data[position] != 0xFF:
            position += 1
            continue
        marker = data[position + 1]
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            position += 2
            continue
        if marker == 0xD9:
            return
        length = int.from_bytes(data[position + 2:position + 4], "big")
        yield marker, data[position + 4:position + 2 + length]
        position += 2 + length


def tables_of(data: bytes):
    found = {}
    for marker, body in segments(data):
        if marker != 0xC4:
            continue
        position = 0
        while position < len(body):
            header = body[position]
            position += 1
            counts = list(body[position:position + 16])
            position += 16
            total = sum(counts)
            symbols = list(body[position:position + total])
            position += total
            found[(header >> 4, header & 0x0F)] = (counts, symbols)
    return found


def main() -> None:
    image = Image.new("RGB", (16, 16))
    for y in range(16):
        for x in range(16):
            image.putpixel((x, y), (x * 16, y * 16, (x + y) * 8))
    handle = io.BytesIO()
    image.save(handle, format="JPEG", quality=90, subsampling=0)
    tables = tables_of(handle.getvalue())

    lines = []
    for (kind, index), (counts, symbols) in sorted(tables.items()):
        name = "luminance" if index == 0 else "chrominance"
        part = "dc" if kind == 0 else "ac"
        lines.append(
            "let %s_%s_counts : Array[Int] = [%s]"
            % (name, part, ", ".join(str(value) for value in counts))
        )
        lines.append("")
        lines.append(
            "let %s_%s_symbols : Array[Int] = [%s]"
            % (
                name,
                part,
                "\n  ".join(
                    ", ".join(str(value) for value in symbols[i:i + 16]) + ","
                    for i in range(0, len(symbols), 16)
                ),
            )
        )
        lines.append("")

    header = """\
// Generated by scripts/fixtures/jpeg_tables.py. Do not edit.
//
// The four Huffman tables a baseline JPEG names for itself, read out of a file a
// mature encoder wrote rather than typed out from the standard: the numbers are
// the standard's, and copying them by hand is how an encoder ends up writing
// files that no decoder can read."""
    moonbit.write(TARGET, header, "\n".join(lines).rstrip() + "\n")
    print("tables: %s" % ", ".join("%s %s" % (k, v) for k, v in sorted(tables.items())))


if __name__ == "__main__":
    main()
