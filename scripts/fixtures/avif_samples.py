"""Generate AVIF samples, and the planes another decoder produced from them.

AV1 is a normative codec: every conformant decoder produces the same samples
from the same bitstream, so a still AVIF has one right answer and a decoder can
be held to it whole-plane for whole-plane rather than to a tolerance.

The samples are written by libavif through Pillow and decoded by ffmpeg, which
uses libdav1d. The fixture records the file's bytes and the digest of the three
planes ffmpeg produced, so the test can decode the file in the four MoonBit
backends — none of which has a file system or a reference decoder — and compare.

    python3 scripts/fixtures/avif_samples.py

`ffmpeg` has to be on the path to regenerate the committed fixture; running the
tests does not need it.
"""

import argparse
import io
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

import moonbit  # noqa: E402
import sources  # noqa: E402
from PIL import Image  # noqa: E402

# The shapes this decoder reproduces exactly. The four below them are the ones
# it does not yet: each is a stream whose blocks run past the first sixteen
# pixels, and at the third or fourth block the arithmetic decoder's state drifts
# from the reference's while the symbols it reads still come out the same. They
# are kept here, commented out rather than deleted, because they are the test
# that has to pass next.
SAMPLES = [
    ("flat-16", (16, 16), "flat", dict(quality=50, speed=9)),
    ("flat-32", (32, 24), "flat", dict(quality=50, speed=9)),
    ("gradient-16", (16, 16), "gradient", dict(quality=60, speed=9)),
    # ("gradient-32", (32, 24), "gradient", dict(quality=45, speed=8)),
    # ("pattern-48", (48, 32), "pattern", dict(quality=40, speed=8)),
    # ("pattern-64", (64, 48), "pattern", dict(quality=75, speed=8)),
    # ("noise-32", (32, 32), "noise", dict(quality=30, speed=8)),
]


def picture(kind: str, size) -> Image.Image:
    width, height = size
    if kind == "flat":
        return Image.new("RGB", size, (96, 128, 160))
    if kind == "gradient":
        out = Image.new("RGB", size)
        out.putdata([
            (x * 255 // max(width - 1, 1), y * 255 // max(height - 1, 1), 128)
            for y in range(height)
            for x in range(width)
        ])
        return out
    if kind == "noise":
        out = Image.new("RGB", size)
        value = 12345
        pixels = []
        for _ in range(width * height):
            value = (value * 1103515245 + 12345) & 0x7FFFFFFF
            pixels.append(((value >> 16) & 0xFF, (value >> 8) & 0xFF, value & 0xFF))
        out.putdata(pixels)
        return out
    return sources.pattern(width, height).convert("RGB")


def decode_with_ffmpeg(data: bytes, work: Path) -> tuple:
    path = work / "sample.avif"
    path.write_bytes(data)
    outcome = subprocess.run(
        [
            "ffmpeg", "-v", "error", "-i", str(path),
            "-f", "rawvideo", "-pix_fmt", "yuv420p", "-",
        ],
        capture_output=True,
    )
    if outcome.returncode != 0:
        sys.exit("ffmpeg could not decode the sample: " + outcome.stderr.decode())
    return outcome.stdout


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=ROOT / "src/avif/decode_samples_wbtest.mbt",
    )
    arguments = parser.parse_args()

    entries = []
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        for name, size, kind, options in SAMPLES:
            image = picture(kind, size)
            handle = io.BytesIO()
            image.save(handle, format="AVIF", **options)
            data = handle.getvalue()
            planes = decode_with_ffmpeg(data, work)
            width, height = size
            expected = width * height + 2 * ((width + 1) // 2) * ((height + 1) // 2)
            if len(planes) != expected:
                sys.exit("ffmpeg returned %d bytes for %s, not %d" %
                         (len(planes), name, expected))
            entries.append((name, width, height, data, moonbit.digest(planes)))
            print("%-12s %4d %4d %6d bytes  %s" %
                  (name, width, height, len(data), moonbit.digest(planes)))

    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Generated by scripts/fixtures/avif_samples.py. Do not edit.",
        "//",
        "// AVIF files written by libavif, and the digest of the luma and two",
        "// chroma planes libdav1d produced from each. A decoder that is one sample",
        "// out anywhere changes the digest.",
        "",
        "///|",
        "/// The name, size and bytes of each sample, with the digest of the planes",
        "/// another decoder made of it.",
        "let avif_samples : Array[(String, Int32, Int32, Bytes, String)] = [",
    ]
    for name, width, height, data, digest in entries:
        lines.append("  (")
        lines.append('    "%s",' % name)
        lines.append("    %d," % width)
        lines.append("    %d," % height)
        lines.append("    " + moonbit.literal(data).replace("\n", "\n    ") + ",")
        lines.append('    "%s",' % digest)
        lines.append("  ),")
    lines.append("]")
    lines.append("")
    arguments.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote %s" % arguments.out)


if __name__ == "__main__":
    main()
