"""Generating the VP8 constant tables from the specification.

    python scripts/fixtures/vp8_tables.py

The tables are large — a thousand coefficient probabilities, nine hundred
subblock mode probabilities, two hundred and fifty-six quantiser steps — and
every one of them has to be exactly right or the arithmetic decoder desynchronises
on the first macroblock. They are read out of the RFC's own text rather than
transcribed by hand.

The RFC is fetched into .cache/, so a rerun does not need the network.
"""

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / ".cache" / "rfc6386.txt"
TARGET = ROOT / "src" / "webp" / "vp8_tables.mbt"

RFC = "https://www.rfc-editor.org/rfc/rfc6386.txt"


def specification() -> str:
    if CACHE.exists():
        return CACHE.read_text(encoding="utf-8")
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(RFC, timeout=120) as response:
        text = response.read().decode("utf-8")
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(text, encoding="utf-8")
    return text


def array_after(text: str, declaration: str, count: int) -> list[int]:
    """The integers of the first array whose declaration contains `declaration`.

    The RFC wraps its tables across pages and interleaves the page footers, so
    the block is taken as everything between the declaration and the closing
    brace, with anything that is not a number dropped.
    """
    start = -1
    search = 0
    while True:
        candidate = text.index(declaration, search)
        brace = text.index("{", candidate)
        # The RFC mentions each table once before defining it, in a sentence
        # that ends with a semicolon. The definition is the one with an `=`.
        # The declaration and its opening brace are adjacent; a mention in
        # running text is followed by another table's brace much further on.
        if brace - candidate < 200 and text[candidate:brace].rstrip().endswith("="):
            start = brace
            break
        search = candidate + 1
    depth = 0
    end = start
    while end < len(text):
        if text[end] == "{":
            depth += 1
        elif text[end] == "}":
            depth -= 1
            if depth == 0:
                break
        end += 1
    body = text[start:end]
    # Page breaks put "Bankoski, et al." and a page number inside the array.
    body = re.sub(r"Bankoski.*?\[Page \d+\]", "", body, flags=re.S)
    body = re.sub(r"RFC 6386.*?\n", "", body)
    numbers = [int(token) for token in re.findall(r"-?\d+", body)]
    # The declaration itself contains numbers (dimensions, the count of the
    # array), so the values are the tail of the list.
    values = numbers[-count:]
    if len(values) != count:
        raise SystemExit(
            "expected %d values for %s, found %d" % (count, declaration, len(values))
        )
    return values


# The four diagonal predictors are numbered differently in two places in the
# specification: the enumeration in section 11.2 lists the down-left one before
# the down-right one, and the table in section 11.5 is printed in that order,
# while the tree that actually codes the modes emits them in the other order —
# down-right, then vertical-right, then down-left. Every encoder follows the
# tree, so the table has to be re-indexed into tree order: row and column 4, 5
# and 6 are cycled. Without this the first row of subblocks decodes correctly
# and everything after it turns to noise, which is a memorable way to learn it.
TREE_ORDER = [0, 1, 2, 3, 5, 6, 4, 7, 8, 9]


def to_tree_order(values: list[int]) -> list[int]:
    out = []
    for above in range(10):
        for left in range(10):
            at = (TREE_ORDER[above] * 10 + TREE_ORDER[left]) * 9
            out.extend(values[at:at + 9])
    return out


def chunked(values: list[int], per_line: int = 16) -> str:
    lines = []
    for index in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(v) for v in values[index:index + per_line]) + ",")
    return "\n".join(lines)


def main() -> None:
    text = specification()
    dc = array_after(text, "dc_qlookup[QINDEX_RANGE] =", 128)
    ac = array_after(text, "ac_qlookup[QINDEX_RANGE] =", 128)
    coeff = array_after(text, "coeff_update_probs [4] [8] [3] [num_dct_tokens-1] =", 4 * 8 * 3 * 11)
    bmode = to_tree_order(
        array_after(text, "kf_bmode_prob [num_intra_bmodes] [num_intra_bmodes]", 10 * 10 * 9)
    )
    defaults = array_after(
        text, "default_coeff_probs [4] [8] [3] [num_dct_tokens - 1] =", 4 * 8 * 3 * 11
    )
    out = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/fixtures/vp8_tables.py from RFC 6386. Do not edit.",
        "",
        "// The quantiser steps, indexed by the quantiser index. The DC table rises",
        "// more slowly than the AC one, because a DC coefficient carries the block's",
        "// average brightness and quantising it hard is what produces banding.",
        "///|",
        "let dc_quant : Array[Int] = [",
        chunked(dc),
        "]",
        "",
        "///|",
        "let ac_quant : Array[Int] = [",
        chunked(ac),
        "]",
        "",
        "// The probabilities that a coefficient probability is updated in the frame",
        "// header: [block type][band][context][token]. A 255 means the encoder never",
        "// changes it, which is why most of the table is 255.",
        "///|",
        "let coeff_update : Array[Int] = [",
        chunked(coeff),
        "]",
        "",
        "// The probabilities a key frame starts from, before the header updates any",
        "// of them: [block type][band][context][token].",
        "///|",
        "let default_coeff_probs : Array[Int] = [",
        chunked(defaults),
        "]",
        "",
        "// Subblock mode probabilities in a key frame, indexed by the mode above and",
        "// the mode to the left, then by the tree's nine interior nodes.",
        "///|",
        "let bmode_probs : Array[Int] = [",
        chunked(bmode, 9),
        "]",
    ]
    TARGET.write_text("\n".join(out), encoding="utf-8")
    print("wrote", TARGET, len(dc), len(ac), len(coeff), len(defaults), len(bmode))


if __name__ == "__main__":
    main()
